const FEUD = [];
(function () {
  let cur = null;
  FEUD_TEXT.split('\n').forEach(l => {
    l = l.trim();
    if (!l) return;
    if (l[0] === '#') { cur = { q: l.slice(1).trim(), a: [] }; FEUD.push(cur); return; }
    const p = l.split('|').map(x => x.trim());
    cur.a.push({ t: p[0], p: +p[1] });
  });
  FEUD.forEach(f => f.a.sort((x, y) => y.p - x.p));
})();
