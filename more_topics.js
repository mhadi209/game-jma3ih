function addTopics(text) {
  let cur = null;
  text.split('\n').forEach(line => {
    line = line.trim(); if (!line) return;
    if (line[0] === '#') { cur = line.slice(1).trim(); if (!TOPICS[cur]) { TOPICS[cur] = []; DESC[cur] = {}; } return; }
    const i = line.indexOf('='); const w = (i > 0 ? line.slice(0, i) : line).trim();
    if (!w || Object.values(TOPICS).some(a => a.includes(w))) return;
    TOPICS[cur].push(w); if (i > 0) DESC[cur][w] = line.slice(i + 1).trim();
  });
}
