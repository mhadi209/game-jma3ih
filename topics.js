const TOPICS = {}, DESC = {};
(function () {
  let cur = null;
  TOPIC_TEXT.split('\n').forEach(line => {
    line = line.trim();
    if (!line) return;
    if (line[0] === '#') { cur = line.slice(1).trim(); TOPICS[cur] = []; DESC[cur] = {}; return; }
    const i = line.indexOf('=');
    const w = (i < 0 ? line : line.slice(0, i)).trim();
    TOPICS[cur].push(w);
    if (i > 0) DESC[cur][w] = line.slice(i + 1).trim();
  });
})();
